export const BLOX_FRUITS = new Proxy(ALL_BLOX_FRUITS, {
  get(_target, prop) {
    const effective = getEffectiveBloxFruits();
    if (prop === 'length') return effective.length;
    if (typeof prop === 'string' && !isNaN(Number(prop))) {
      return effective[Number(prop)];
    }
    const val = (effective as any)[prop];
    if (typeof val === 'function') {
      return val.bind(effective);
    }
    return val;
  },
  ownKeys() {
    const effective = getEffectiveBloxFruits();
    return Reflect.ownKeys(effective);
  },
  getOwnPropertyDescriptor(_target, prop) {
    const effective = getEffectiveBloxFruits();
    return Object.getOwnPropertyDescriptor(effective, prop) || {
      configurable: true,
      enumerable: true,
      writable: true,
      value: (effective as any)[prop],
    };
  },
});

